class Student
{
    int id;
    String name;
    String email;
    String phone;
    String course;
    int year;

    Student(int id, String name, String email,
            String phone, String course, int year)
    {
        this.id = id;
        this.name = name;
        this.email = email;
        this.phone = phone;
        this.course = course;
        this.year = year;
    }
}